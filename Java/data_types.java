// Java program to demonstrate the data types in Java.
/* Data types are the classification or categorization of data items. It represents the
 kind of value that tells what operations can be performed on a particular data. Since
  everything is an object in Java (Single root hierarchy as everything gets derived from
   java.lang.Object), data types are actually objects. Data types are divided into two
    groups: Primitive data types and Non-primitive data types. */
public class data_types {
    public static void main(String args[]){
        int a=10;//integer data type
        float b=10.5f;//float data type
        double c=10.5;//double data type
        char d='A';//character data type
        String e="Hello";//String data type
        System.out.println("Integer: "+a);
        System.out.println("Float: "+b);
        System.out.println("Double: "+c);
        System.out.println("Character: "+d);
        System.out.println("String: "+e);
    }
    
}

//try incr and decr operator on java variable
public class Q4 {
    public static void main(String[] args) {
        int a=10;
        System.out.println("a : "+a);
        System.out.println("a : "+ ++a);
        System.out.println("a : "+ a++);
        int b=5;
        System.out.println("a : "+ --b);
        System.out.println("a : "+b--);
    }
}
